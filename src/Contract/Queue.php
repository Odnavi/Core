<?php

namespace Odnavi\Core\Contract;

/**
 * Контракт очереди отложенных задач. По умолчанию используется SyncQueue
 * (выполняет задачу немедленно); приложение может внедрить свою реализацию
 * (RabbitMQ и т.п.) через QueueRegistry::set() — сам пакет не привязан
 * к конкретному брокеру.
 *
 * В сообщение кладётся имя задачи и скалярный payload, а не сущности:
 * пока сообщение лежит в очереди, данные в БД могут измениться, поэтому
 * обработчик поднимает их заново по идентификаторам.
 */
interface Queue
{
    /**
     * Публикует задачу в очередь.
     *
     * @param string  $job     Имя задачи из белого списка обработчиков.
     * @param array   $payload Скалярные данные, достаточные для восстановления задачи.
     * @param ?string $app     Приложение-адресат, если задача ставится не своему
     *                         приложению. Payload тогда обязан быть самодостаточным:
     *                         чужой консьюмер читает другую базу, и идентификаторы
     *                         из своей там ничего не значат.
     */
    public function publish(string $job, array $payload = [], ?string $app = null): void;

    /**
     * Читает очередь и передаёт задачи обработчику. Блокирующий вызов:
     * возвращает управление, только когда consumer должен завершиться.
     *
     * @param callable  $handler    fn(string $job, array $payload, array $meta): void —
     *                              бросает исключение, если задача не выполнена.
     * @param ?callable $shouldStop fn(): bool — проверяется после подтверждения
     *                              каждого сообщения; true завершает чтение.
     */
    public function consume(callable $handler, ?callable $shouldStop = null): void;
}
